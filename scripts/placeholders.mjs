// Collects every [[PLACEHOLDER: …]] token in the source and content into content/PLACEHOLDERS.md.
//   node scripts/placeholders.mjs          → regenerate the file
//   node scripts/placeholders.mjs --check  → fail if the file is out of date (used in CI)
import fs from 'node:fs';
import path from 'node:path';

const ROOTS = ['app', 'components', 'content', 'lib', 'messages'];
const OUT = 'content/PLACEHOLDERS.md';
const TOKEN = /\[\[PLACEHOLDER[^\]]*\]\]/g;

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(p);
    else if (/\.(tsx?|mdx|json)$/.test(entry.name)) yield p;
  }
}

const found = new Map(); // token -> Set(files)
for (const root of ROOTS) {
  for (const file of walk(root)) {
    if (file === OUT) continue;
    const text = fs.readFileSync(file, 'utf8');
    for (const m of text.matchAll(TOKEN)) {
      if (!found.has(m[0])) found.set(m[0], new Set());
      found.get(m[0]).add(file.split(path.sep).join('/'));
    }
  }
}

const groups = {
  'Results, metrics and stats':
    /(%|metric|increase|rate|sales|leads|users|revenue|traffic|uptime|projects|satisfaction|enquir|demandes|ventes|prospects|trafic|utilisateurs|revenu|disponibilité|keywords|mots-clés|return|retour|cost per|coût|booked|appels|load time|chargement|number|nombre|weeks to|semaines avant|price increase|tarifs)/i,
  'Clients, quotes and logos':
    /(client|quote|citation|logo|testimonial|founder quote|fondateur sur|role, company|fonction)/i,
  'Business terms and promises':
    /(guarantee|garantie|response time|délai de réponse|launch time|délai de lancement|revision|révision|payment|paiement|turnaround|délai pour|learning|apprentissage|time to first|premiers résultats|concepts|pistes)/i,
  'Integrations and assets':
    /(cal\.com|lead magnet|guide offert|photo|portrait|screenshot|capture)/i,
  'Legal (for the lawyer)': /(lawyer|juriste|address|adresse|registration|immatriculation)/i,
};

const sorted = [...found.entries()].sort(([a], [b]) => a.localeCompare(b));
const bucket = new Map(Object.keys(groups).map((g) => [g, []]));
bucket.set('Other', []);
for (const [token, files] of sorted) {
  const g = Object.entries(groups).find(([, re]) => re.test(token))?.[0] ?? 'Other';
  bucket.get(g).push([token, files]);
}

let md = `# Placeholders to replace before launch

Generated by \`npm run placeholders\`. Do not edit by hand: replace the token in the listed file(s), then regenerate.
CI runs \`npm run placeholders:check\` and fails if this list is out of date.

Every value below is shown on the site with a visible highlight. **Never replace a placeholder with an invented
result, client name or testimonial.** Use real, client-approved figures only.

**${found.size} unique placeholders** in ${new Set(sorted.flatMap(([, f]) => [...f])).size} files.

## Copy to approve (not tokens)

- Founder message on About and the founder quote on Home: drafted for Tanwi Kalson to approve or rewrite (\`messages/en.json\` → \`about.founderBody\`, \`home.founder\`; same keys in \`messages/fr.json\`).
- All French copy is marked \`review: pending\` for a native speaker (\`messages/fr.json\`, \`content/services/fr.ts\`, \`content/**/fr/*.mdx\`).
- Legal pages are drafts for a qualified lawyer (\`content/legal/**\`).
- Blog posts ship with \`status: draft\` (shown with a Draft badge, \`noindex\`, left out of the sitemap). Set \`status: published\` once reviewed.
`;
for (const [g, items] of bucket) {
  if (!items.length) continue;
  md += `\n## ${g}\n\n| Placeholder | Where |\n| --- | --- |\n`;
  for (const [token, files] of items) {
    md += `| \`${token.replace(/\|/g, '\\|')}\` | ${[...files].map((f) => `\`${f}\``).join('<br>')} |\n`;
  }
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== md) {
    console.error(`${OUT} is out of date. Run: npm run placeholders`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${found.size} placeholders).`);
} else {
  fs.writeFileSync(OUT, md);
  console.log(`Wrote ${OUT} (${found.size} placeholders).`);
}
